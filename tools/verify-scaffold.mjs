#!/usr/bin/env node
// Write verify/'s package.json and entry point from the manifest.
//
//   node tools/verify-scaffold.mjs
//
// verify/ is not shipped and not in the registry. It exists to answer one
// question the registry JSON cannot: does this source actually build. Its
// dependency list is derived rather than maintained, because a hand-kept copy
// of 40-odd package names goes stale the first time upstream adds one.

import { writeFile, mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ITEMS } from '../src/manifest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'verify');

const imported = ITEMS.filter(i => i.tier === 'component' && i.files?.length);
const npm = [...new Set(imported.flatMap(i => i.npm ?? []))].sort();

/* Peers the imported source imports without declaring — upstream assumes a
 * Next.js app is already there. A verify app is not one, so they are named
 * here rather than discovered as a build failure. */
const IMPLIED = ['next', 'next-themes'];

/* Pinned, not latest. @react-three/fiber@9.7 declares peer react ">=19 <19.3"
 * and React shipped 19.3, so `latest` cannot be installed alongside the seven
 * WebGL items. This is a real constraint on anyone installing them, not a
 * quirk of this app — measured 2026-09-19. */
const PINNED = {
  react: '~19.2.0',
  'react-dom': '~19.2.0',

  /* Three shadcn primitives upstream copied at an older major of their library,
   * and the libraries have since renamed things. react-resizable-panels@4
   * renamed PanelGroup to Group, so `ResizablePrimitive.PanelGroup` is undefined
   * at render — and a namespace import means the bundler never complains. The
   * component builds and then throws. Measured 2026-09-20; tsc is what found it. */
  'react-resizable-panels': '^2.1.9',
  recharts: '^2.15.4',
  'react-day-picker': '^9.11.1',
};

const pkg = {
  name: 'amirsalmani-suite-verify',
  private: true,
  type: 'module',
  description: 'Proves the component tier builds. Not shipped, not in the registry.',
  scripts: {
    build: 'vite build',
    dev: 'vite',
    typecheck: 'tsc --noEmit',
  },
  dependencies: {
    ...Object.fromEntries([...new Set([...npm, ...IMPLIED])].sort().map(d => [d, 'latest'])),
    ...PINNED,
  },
  devDependencies: {
    '@tailwindcss/vite': 'latest',
    '@types/react': 'latest',
    '@types/react-dom': 'latest',
    '@vitejs/plugin-react': 'latest',
    tailwindcss: 'latest',
    typescript: 'latest',
    vite: 'latest',
  },
};

await mkdir(path.join(OUT, 'src'), { recursive: true });
await writeFile(path.join(OUT, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');

/* One import per item, so a module that does not parse fails the build rather
 * than sitting unreferenced and unchecked. Named exports are not knowable from
 * the registry, so this imports for side effects and asserts the module loaded. */
const lines = imported.map(i => {
  const entry = i.files.find(f => /\.(tsx|jsx)$/.test(f.path)) ?? i.files[0];
  return `import * as ${ident(i.name)} from '@suite/${entry.path.replace(/\.(tsx|jsx|ts|js)$/, '')}';`;
});

const body = `/* Generated by tools/verify-scaffold.mjs. Do not edit. */
${lines.join('\n')}

const modules = {
${imported.map(i => `  '${i.name}': ${ident(i.name)},`).join('\n')}
};

const empty = Object.entries(modules).filter(([, m]) => Object.keys(m).length === 0);
if (empty.length) {
  throw new Error(\`\${empty.length} module(s) exported nothing: \${empty.map(([n]) => n).join(', ')}\`);
}
console.log(\`\${Object.keys(modules).length} modules loaded\`);
export default modules;
`;
await writeFile(path.join(OUT, 'src', 'every-item.generated.ts'), body);

function ident(name) { return 'M_' + name.replace(/[^a-z0-9]/gi, '_'); }

console.log(`verify/ — ${imported.length} items · ${Object.keys(pkg.dependencies).length} dependencies`);
